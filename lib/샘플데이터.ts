// 신청한 때를 따로 안 적은 신청은 그 클래스가 열리기 하루 전 12:00
function 하루전(클래스id: string): 신청한때 {
  const 클래스 = 클래스목록.find((c) => c.id === 클래스id)!;
  return { 날: 클래스.날 - 1, 시: 12, 분: 0 };
}

let 번호 = 0;
function 신청만들기(
  수강생id: string,
  클래스id: string,
  상태: 신청상태,
  옵션: { 출석?: boolean; 신청한때?: 신청한때 } = {},
): 신청 {
  번호 += 1;
  return {
    id: `a${번호}`,
    수강생id,
    클래스id,
    상태,
    출석: 옵션.출석 ?? false,
    신청한때: 옵션.신청한때 ?? 하루전(클래스id),
  };
}

